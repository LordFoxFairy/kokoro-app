import { expect, test } from "@playwright/test"

// This is the existing preview transport, not evidence of an owner-backed save.
for (const viewport of [{ width: 390, height: 844 }, { width: 390, height: 420 }, { width: 320, height: 360 }]) {
  test(`项目指令菜单在 ${viewport.width}×${viewport.height} 保留编辑滚动区和键盘可达的独立footer`, async ({ page }, testInfo) => {
    await page.setViewportSize(viewport)
    await page.addInitScript(() => localStorage.setItem("kokoro.locale", "zh"))
    await page.goto("/app/project/preview-project")
    const trigger = page.locator('[data-slot="workspace-header"]').getByRole("button", { name: "项目选项", exact: true })
    await trigger.focus()
    await trigger.press("ArrowDown")
    const entry = page.getByRole("menuitem", { name: "编辑指令", exact: true })
    await entry.focus()
    await entry.press("Enter")
    const dialog = page.getByRole("dialog", { name: "项目指令", exact: true })
    const editor = dialog.getByRole("textbox", { name: "项目指令", exact: true })
    await expect(editor).toBeFocused()
    const instruction = "保留完整长指令\n".repeat(80)
    await editor.fill(instruction)
    await editor.press("ControlOrMeta+End")
    const textarea = await editor.boundingBox()
    const footer = await dialog.locator('[data-slot="dialog-footer"]').boundingBox()
    const frame = await dialog.boundingBox()
    expect(textarea).not.toBeNull()
    expect(footer).not.toBeNull()
    expect(frame).not.toBeNull()
    if (!textarea || !footer || !frame) throw new Error("instruction editor geometry unavailable")
    expect(textarea.y + textarea.height).toBeLessThanOrEqual(footer.y + 0.1)
    expect(frame.y).toBeGreaterThanOrEqual(0)
    expect(frame.y + frame.height).toBeLessThanOrEqual(viewport.height)
    expect(await editor.evaluate((node) => node.scrollHeight > node.clientHeight && node.scrollTop > 0)).toBe(true)
    await page.keyboard.press("Tab")
    await expect(dialog.getByRole("button", { name: "历史记录", exact: true })).toBeFocused()
    await page.keyboard.press("Tab")
    await expect(dialog.getByRole("button", { name: "取消", exact: true })).toBeFocused()
    await page.keyboard.press("Tab")
    const save = dialog.getByRole("button", { name: "保存", exact: true })
    await expect(save).toBeFocused()
    await expect(save).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath("instruction-editor.png"), fullPage: true })
    await page.keyboard.press("Enter")
    await expect(dialog).toBeHidden()
    await expect(trigger).toBeFocused()
    await expect.poll(() => page.evaluate(() => localStorage.getItem("kokoro.preview.project.preview-project.instructions"))).toBe(instruction)
    await page.reload()
    await trigger.click()
    await page.getByRole("menuitem", { name: "编辑指令", exact: true }).click()
    await expect(editor).toHaveValue(instruction)
  })
}
