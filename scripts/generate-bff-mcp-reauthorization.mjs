import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
function renderSchema(schema) {
  if (schema.not && Object.keys(schema.not).length === 0) return "z.never()";
  if ("const" in schema) return `z.literal(${JSON.stringify(schema.const)})`;
  const variants = schema.oneOf ?? schema.anyOf;
  if (variants) return variants.length === 1 ? renderSchema(variants[0]) : `z.union([${variants.map(renderSchema).join(", ")}])`;
  if (schema.enum) { assert.equal(schema.type, "string"); return `z.enum(${JSON.stringify(schema.enum)})`; }
  if (schema.type === "object") {
    if (!schema.properties && typeof schema.additionalProperties === "object") return `z.record(${renderSchema(schema.propertyNames ?? { type: "string" })}, ${renderSchema(schema.additionalProperties)})`;
    assert.equal(schema.additionalProperties, false, "lookup objects must stay closed");
    return `z.object({${Object.entries(schema.properties).map(([key, value]) => `${JSON.stringify(key)}: ${renderSchema(value)}${schema.required?.includes(key) ? "" : ".optional()"}`).join(", ")}}).strict()`;
  }
  if (schema.type === "array") return `z.array(${renderSchema(schema.items)})${schema.minItems === undefined ? "" : `.min(${schema.minItems})`}${schema.maxItems === undefined ? "" : `.max(${schema.maxItems})`}`;
  if (schema.type === "boolean") return "z.boolean()";
  if (schema.type === "integer") return `z.number().int()${schema.minimum === undefined ? "" : `.min(${schema.minimum})`}${schema.maximum === undefined ? "" : `.max(${schema.maximum})`}`;
  assert.equal(schema.type, "string");
  return `z.string()${schema.minLength === undefined ? "" : `.min(${schema.minLength})`}${schema.maxLength === undefined ? "" : `.max(${schema.maxLength})`}${schema.format === "date-time" ? ".datetime({ offset: true })" : ""}${schema.pattern ? `.regex(new RegExp(${JSON.stringify(schema.pattern)}, "u"))` : ""}`;
}

export function renderMcpReauthorization(bytes, provenance) {
  assert.equal(provenance.owner, "kokoro-bff"); assert.equal(provenance.candidate, false);
  assert.match(provenance.owner_commit, /^[a-f0-9]{40}$/u);
  assert.equal(provenance.source_path, "contract/openapi/browser/v1/mcp-reauthorization.json");
  assert.equal(createHash("sha256").update(bytes).digest("hex"), provenance.source_sha256);
  const spec = JSON.parse(bytes.toString("utf8")), policy = spec["x-kokoro-reauthorization-policy"];
  assert.equal(policy.profile, provenance.profile); assert.equal(policy.version, provenance.profile_version); assert.equal(spec.info.version, provenance.profile_version);
  assert.equal(policy.visibility, "browser-private"); assert.equal(policy.path, "/browser/v1/mcp/servers/{server_id}/reauthorize");
  for (const field of ["automatic_retries", "new_command_authorized", "prepare_authorized", "connected"]) assert.equal(policy[field], false);
  assert.deepEqual(Object.keys(spec.paths), [policy.path]); const operation = spec.paths[policy.path].post;
  assert.equal(operation.operationId, "reauthorizePersonalMcpServer"); assert.equal(operation["x-kokoro-permission"], "mcp_personal.manage");
  const request = operation.requestBody.content["application/json"].schema;
  assert.deepEqual(request.required, ["source_connector_id", "expected_server_state_version", "expected_connector_state_version"]);
  const errors = Object.entries(operation.responses).filter(([status]) => status !== "200");
  return `// Generated by scripts/generate-bff-mcp-reauthorization.mjs; do not edit.
import { z } from "zod";
export const MCP_REAUTHORIZATION_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const;
export const MCP_REAUTHORIZATION_POLICY = ${JSON.stringify(policy, null, 2)} as const;
export const mcpReauthorizationServerIdSchema = ${renderSchema(operation.parameters[0].schema)};
export const mcpReauthorizationKeySchema = ${renderSchema(operation.parameters[1].schema)};
export const mcpReauthorizationRequestSchema = ${renderSchema(request)};
export const mcpReauthorizationWireSchema = ${renderSchema(operation.responses[200].content["application/json"].schema)};
export const mcpReauthorizationErrors = {
${errors.map(([status, value]) => `${JSON.stringify(status)}: ${renderSchema(value.content["application/json"].schema)}`).join(",\n")}
} as const;
`;
}
async function main() {
  const mode = process.argv[2]; assert.ok(mode === "--write" || mode === "--check");
  const provenance = JSON.parse(await readFile(new URL("contract/bff-mcp-reauthorization-source.json", root), "utf8"));
  const content = renderMcpReauthorization(await readFile(new URL("src/generated/bff-mcp-reauthorization.json", root)), provenance);
  const output = new URL("src/generated/bff-mcp-reauthorization.ts", root);
  if (mode === "--write") await writeFile(output, content); else assert.equal(await readFile(output, "utf8"), content, "generated MCP reauthorization drift");
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
