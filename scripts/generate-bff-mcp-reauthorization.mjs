import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
function render(s) {
  if (s.not && Object.keys(s.not).length === 0) return "z.never()";
  if ("const" in s) return `z.literal(${JSON.stringify(s.const)})`;
  const variants = s.oneOf ?? s.anyOf;
  if (variants) return variants.length === 1 ? render(variants[0]) : `z.union([${variants.map(render).join(", ")}])`;
  if (s.enum) return `z.enum(${JSON.stringify(s.enum)})`;
  if (s.type === "object") {
    if (!s.properties && typeof s.additionalProperties === "object") return `z.record(${render(s.propertyNames ?? {type: "string"})}, ${render(s.additionalProperties)})`;
    assert.equal(s.additionalProperties, false);
    return `z.object({${Object.entries(s.properties).map(([k,v]) => `${JSON.stringify(k)}: ${render(v)}${s.required?.includes(k) ? "" : ".optional()"}`).join(", ")}}).strict()`;
  }
  if (s.type === "array") return `z.array(${render(s.items)})${s.minItems === undefined ? "" : `.min(${s.minItems})`}${s.maxItems === undefined ? "" : `.max(${s.maxItems})`}`;
  if (s.type === "boolean") return "z.boolean()";
  if (s.type === "integer") return `z.number().int()${s.minimum === undefined ? "" : `.min(${s.minimum})`}${s.maximum === undefined ? "" : `.max(${s.maximum})`}`;
  assert.equal(s.type,"string");
  return `z.string()${s.minLength === undefined ? "" : `.min(${s.minLength})`}${s.maxLength === undefined ? "" : `.max(${s.maxLength})`}${s.format === "date-time" ? ".datetime({ offset: true })" : ""}${s.pattern ? `.regex(new RegExp(${JSON.stringify(s.pattern)}, "u"))` : ""}`;
}
export function renderMcpReauthorization(bytes, provenance) {
  assert.equal(provenance.owner, "kokoro-bff"); assert.equal(provenance.candidate, false);
  assert.match(provenance.owner_commit, /^[a-f0-9]{40}$/u);
  assert.equal(provenance.source_path, "contract/openapi/browser/v1/mcp-reauthorization.json");
  assert.equal(createHash("sha256").update(bytes).digest("hex"),provenance.source_sha256);
  const spec=JSON.parse(bytes), policy=spec["x-kokoro-reauthorization-policy"];
  assert.equal(policy.profile,provenance.profile); assert.equal(policy.version,provenance.profile_version); assert.equal(spec.info.version,policy.version);
  assert.equal(policy.visibility,"browser-private"); assert.equal(policy.permission,"mcp_personal.manage");
  assert.equal(policy.path,"/browser/v1/mcp/servers/{server_id}/reauthorize");
  assert.equal(policy.operation_id,"reauthorizePersonalMcpServer");
  assert.deepEqual(policy.state_version,{ minimum:1,maximum:2147483646,encoding:"canonical_decimal_string" });
  for(const field of ["automatic_retries","new_command_authorized","prepare_authorized","connected"]) assert.equal(policy[field],false);
  assert.deepEqual(policy.same_command,{method:"POST",target:"original",body:"original_source_and_double_cas",key:"original"});
  assert.equal(policy.historical_completed,"original_safe_ack_even_after_delete; never_current_or_execution_qualification");
  assert.deepEqual(spec["x-kokoro-owner-contract"],provenance.platform_owner);
  assert.deepEqual(Object.keys(spec.paths),[policy.path]); assert.deepEqual(Object.keys(spec.paths[policy.path]),["post"]);
  const op=spec.paths[policy.path].post;
  assert.equal(op.operationId,policy.operation_id); assert.equal(op["x-kokoro-owner"],"kokoro-bff");
  assert.deepEqual(op.parameters.map(p=>[p.in,p.name,p.required]),[["path","server_id",true],["header","Idempotency-Key",true]]);
  const request=op.requestBody.content["application/json"].schema;
  assert.deepEqual(request.required,["source_connector_id","expected_server_state_version","expected_connector_state_version"]);
  const wire=op.responses[200].content["application/json"].schema;
  assert.deepEqual(wire.properties.data.required,["server","connector","replayed"]);
  const data=wire.properties.data;
  assert.equal(data.properties.server.properties.status.const,"pending"); assert.equal(data.properties.server.properties.prepare_status.const,"pending_prepare");
  assert.equal(data.properties.connector.properties.status.const,"pending"); assert.equal(data.properties.connector.properties.enabled.const,false); assert.equal(data.properties.connector.properties.state_version.const,"1");
  const errors=Object.entries(op.responses).filter(([status])=>status!=="200");
  const tuples=errors.flatMap(([status,r])=>r.content["application/json"].schema.oneOf.map(s=>({status:Number(status),code:s.properties.error.properties.code.const,retryable:s.properties.error.properties.retryable.const})));
  const sort=xs=>[...xs].sort((a,b)=>a.status-b.status||a.code.localeCompare(b.code));
  assert.deepEqual(sort(tuples),sort(policy.errors)); assert.equal(new Set(tuples.map(t=>`${t.status}:${t.code}:${t.retryable}`)).size,tuples.length);
  return `// Generated by scripts/generate-bff-mcp-reauthorization.mjs; do not edit.\nimport { z } from "zod";\nexport const MCP_REAUTHORIZATION_PROVENANCE = ${JSON.stringify(provenance,null,2)} as const;\nexport const MCP_REAUTHORIZATION_POLICY = ${JSON.stringify(policy,null,2)} as const;\nexport const mcpReauthorizationServerIdSchema = ${render(op.parameters[0].schema)};\nexport const mcpReauthorizationKeySchema = ${render(op.parameters[1].schema)};\nexport const mcpReauthorizationRequestSchema = ${render(request)};\nexport const mcpReauthorizationWireSchema = ${render(wire)};\nexport const mcpReauthorizationErrors = {${errors.map(([status,r])=>`${JSON.stringify(status)}: ${render(r.content["application/json"].schema)}`).join(",\n")}} as const;\n`;
}
async function main(){
  const mode=process.argv[2]; assert.ok(mode==="--write"||mode==="--check");
  const provenance=JSON.parse(await readFile(new URL("contract/bff-mcp-reauthorization-source.json",root),"utf8"));
  const text=renderMcpReauthorization(await readFile(new URL("src/generated/bff-mcp-reauthorization.json",root)),provenance);
  const output=new URL("src/generated/bff-mcp-reauthorization.ts",root);
  if(mode==="--write") await writeFile(output,text); else assert.equal(await readFile(output,"utf8"),text);
  process.stdout.write(`MCP reauthorization ${mode.slice(2)} passed\n`);
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)) await main();
