import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const pin = JSON.parse(await readFile(new URL('contract/bff-auth-session-source.json', root), 'utf8'))
assert.equal(pin.owner, 'kokoro-bff')
assert.equal(pin.owner_commit, '34c9f997a4d86f33be2f815c43cd155ed338fe86')
assert.equal(pin.source_path, 'contract/openapi/browser/v1/auth-session.json')
assert.equal(pin.version, '1.0.0')
const bytes = await readFile(new URL(`contract/vendor/kokoro-bff/${pin.owner_commit}/auth-session.json`, root))
const hash = createHash('sha256').update(bytes).digest('hex')
assert.equal(hash, pin.source_sha256)
assert.equal(hash, 'a7b5876632f6ad91b9fc162c9abcf48b36b2677a3b15a6a497d3305aeaea81ba')
const source = JSON.parse(bytes), policy = source['x-kokoro-auth-session-policy']
assert.equal(source.info.version, pin.version)
assert.equal(policy.refresh_default, true)
const operation = source.paths[policy.path].get
assert.equal(operation.operationId, policy.operation_id)
function render(s) {
 if ('const' in s) return `z.literal(${JSON.stringify(s.const)})`
 if (s.oneOf || s.anyOf) { const variants = (s.oneOf ?? s.anyOf).map(render); return variants.length === 1 ? variants[0] : `z.union([${variants.join(',')}])` }
 if (s.type === 'object') { assert.equal(s.additionalProperties, false); return `z.object({${Object.entries(s.properties).map(([key,value]) => `${JSON.stringify(key)}:${render(value)}${s.required?.includes(key) ? '' : '.optional()'}`).join(',')}}).strict()` }
 if (s.type === 'boolean') return 'z.boolean()'
 assert.equal(s.type, 'string')
 return `z.string()${s.minLength === undefined ? '' : `.min(${s.minLength})`}${s.pattern ? `.regex(new RegExp(${JSON.stringify(s.pattern.replace(/\$$/u, '(?![\\s\\S])'))},'u'))` : ''}${s.format === 'date-time' ? '.datetime()' : ''}`
}
const schemas = Object.entries(operation.responses).map(([status,response]) => [status,render(response.content['application/json'].schema)])
const output = `// Generated by scripts/generate-bff-auth-session.mjs. Do not edit.\nimport { z } from 'zod'\nexport const browserAuthSessionProvenance=${JSON.stringify(pin)} as const\nexport const browserAuthSessionPolicy=${JSON.stringify(policy)} as const\nexport const browserAuthSessionResponseSchema=${schemas.find(([status]) => status === '200')[1]}\nexport type BrowserAuthSession=z.infer<typeof browserAuthSessionResponseSchema>['data']\nexport const browserAuthSessionErrorSchemas={${schemas.filter(([status]) => status !== '200').map(([status,schema]) => `${status}:${schema}`).join(',')}}\nexport function browserAuthSessionPath(refresh=true):string { return browserAuthSessionPolicy.path+'?refresh='+String(refresh) }\n`
const destination = new URL(process.env.AUTH_SESSION_OUTPUT ?? 'src/generated/bff-auth-session.ts', root)
assert.ok(['--write','--check'].includes(process.argv[2]))
if (process.argv[2] === '--write') { await mkdir(new URL('.',destination),{recursive:true}); await writeFile(destination,output) }
else assert.equal(await readFile(destination,'utf8'),output,'BFF browser auth session generation drift')
