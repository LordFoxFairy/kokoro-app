function render(s) {
  if ("const" in s) return `z.literal(${JSON.stringify(s.const)})`;
  if (s.anyOf) return s.anyOf.length === 1 ? render(s.anyOf[0]) : `z.union([${s.anyOf.map(render).join(", ")}])`;
  if (Array.isArray(s.type)) return `z.union([${s.type.map(type => render({...s, type})).join(", ")}])`;
  if (s.type === "null") return "z.null()";
  if (s.type === "boolean") return "z.boolean()";
  if (s.type === "object") {
    assert.equal(s.additionalProperties, false);
    return `z.object({${Object.entries(s.properties).map(([key,v]) => `${JSON.stringify(key)}: ${render(v)}${s.required?.includes(key)?"":".optional()"}`).join(",\n")}}).strict()`;
  }
  if (s.type === "array") return `z.array(${render(s.items)})${s.minItems === undefined?"":`.min(${s.minItems})`}${s.maxItems === undefined?"":`.max(${s.maxItems})`}`;
  assert.equal(s.type, "string");
  return `z.string()${s.minLength === undefined?"":`.min(${s.minLength})`}${s.maxLength === undefined?"":`.max(${s.maxLength})`}${s.pattern?`.regex(new RegExp(${JSON.stringify(s.pattern)}, "u"))`:""}`;
}
