import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { readFile, writeFile } from "node:fs/promises"
import YAML from "yaml"
const pin = {
  ownerCommit: "38d47c958cecdc072ee60d5a96ad17c48ac691c6",
  sourceSha256: "45c54365e75a31684e1dbf841a0c68cd554bf022643919cac591c78ed4499509",
  openapiVersion: "29.0.0",
}
const bytes = await readFile(new URL("../src/generated/bff-public-openapi.yaml", import.meta.url))
assert.equal(createHash("sha256").update(bytes).digest("hex"), pin.sourceSha256)
const spec = YAML.parse(bytes.toString())
assert.equal(spec.info.version, pin.openapiVersion)
const schemas = spec.components.schemas
function render(s) {
  if (s.$ref) return render(schemas[s.$ref.split("/").at(-1)])
  if (Array.isArray(s.type)) return `z.union([${s.type.map((type) => render({ ...s, type })).join(",")}])`
  if (s.oneOf) return `z.union([${s.oneOf.map(render).join(",")}])`
  if (s.const !== undefined) return `z.literal(${JSON.stringify(s.const)})`
  if (s.type === "null") return "z.null()"
  if (s.type === "boolean") return "z.boolean()"
  if (s.type === "object")
    return `z.object({${Object.entries(s.properties)
      .map(([k, v]) => `${JSON.stringify(k)}:${render(v)}${s.required?.includes(k) ? "" : ".optional()"}`)
      .join(",")}})${s.additionalProperties === false ? ".strict()" : ""}`
  if (s.type === "array")
    return `z.array(${render(s.items)})${s.minItems !== undefined ? `.min(${s.minItems})` : ""}${s.maxItems !== undefined ? `.max(${s.maxItems})` : ""}${s.uniqueItems ? ".refine(values=>new Set(values.map(value=>JSON.stringify(value))).size===values.length)" : ""}`
  let out = s.enum ? `z.enum(${JSON.stringify(s.enum)})` : s.type === "integer" ? "z.number().int()" : "z.string()"
  if (s.minimum !== undefined) out += `.min(${s.minimum})`
  if (s.maximum !== undefined) out += `.max(${s.maximum})`
  if (s.minLength !== undefined) out += `.min(${s.minLength})`
  if (s.maxLength !== undefined) out += `.max(${s.maxLength})`
  if (s.pattern) out += `.regex(new RegExp(${JSON.stringify(s.pattern)},"u"))`
  if (s.format === "date-time") out += ".datetime({offset:true})"
  return out
}
const names = {
  projectAccessSchema: "ProjectAccess",
  projectGrantRequestSchema: "ProjectGrantRequest",
  projectGrantSchema: "ProjectGrant",
  projectAccessResponseSchema: "ProjectAccessResponse",
  projectGrantResponseSchema: "ProjectGrantResponse",
  projectGrantsResponseSchema: "ProjectGrantsResponse",
  projectDeliverySchema: "ProjectDelivery",
  projectArtifactItemSchema: "ProjectArtifactItem",
}
const operations = {
  access: ["/v1/projects/{projectId}/access", "get", "getProjectAccess"],
  list: ["/v1/projects/{projectId}/grants", "get", "listProjectGrants"],
  set: ["/v1/projects/{projectId}/grants/{subject_id}", "put", "setProjectGrant"],
  revoke: ["/v1/projects/{projectId}/grants/{subject_id}", "delete", "revokeProjectGrant"],
}
for (const [path, method, id] of Object.values(operations)) assert.equal(spec.paths[path][method].operationId, id)
const output = `// Generated by scripts/generate-bff-project-access.mjs. Do not edit.\nimport { z } from "zod"\nexport const PROJECT_ACCESS_SOURCE=${JSON.stringify(pin)} as const\nexport const PROJECT_ACCESS_OPERATIONS=${JSON.stringify(operations)} as const\n${Object.entries(
  names,
)
  .map(([name, key]) => `export const ${name}=${render(schemas[key])}`)
  .join(
    "\n",
  )}\nexport const projectCanControlSchema=${render(schemas.ExecutionHead.properties.can_control)}\nexport const projectCanRegenerateSchema=${render(schemas.ChatMessage.properties.can_regenerate)}\nexport type ProjectAccess=z.infer<typeof projectAccessSchema>\nexport type ProjectGrant=z.infer<typeof projectGrantSchema>\nexport type ProjectGrantRequest=z.infer<typeof projectGrantRequestSchema>\n`
const target = new URL("../src/generated/bff-project-access.ts", import.meta.url)
if (process.argv[2] === "--write") await writeFile(target, output)
else {
  assert.equal(process.argv[2], "--check")
  assert.equal(await readFile(target, "utf8"), output)
}
