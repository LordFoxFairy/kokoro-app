function render(s, schemas) {
  if (s.$ref)
    return render(
      schemas[s.$ref.replace("#/components/schemas/", "")],
      schemas,
    );
  if (s.oneOf)
    return `z.union([${s.oneOf.map((x) => render(x, schemas)).join(",")}])`;
  if (s.const !== undefined) return `z.literal(${JSON.stringify(s.const)})`;
  if (s.type === "object") {
    assert.equal(s.additionalProperties, false);
    return `z.object({${Object.entries(s.properties)
      .map(
        ([key, value]) =>
          `${JSON.stringify(key)}:${render(value, schemas)}${s.required.includes(key) ? "" : ".optional()"}`,
      )
      .join(",")}}).strict()`;
  }
  if (s.type === "array")
    return `z.array(${render(s.items, schemas)})${s.minItems === undefined ? "" : `.min(${s.minItems})`}${s.maxItems === undefined ? "" : `.max(${s.maxItems})`}${s.uniqueItems ? ".refine(values => new Set(values.map(value => JSON.stringify(value))).size === values.length)" : ""}`;
  if (s.type === "boolean") return "z.boolean()";
  assert.equal(s.type, "string");
  let text = s.enum ? `z.enum(${JSON.stringify(s.enum)})` : "z.string()";
  if (s.minLength !== undefined) text += `.min(${s.minLength})`;
  if (s.maxLength !== undefined) text += `.max(${s.maxLength})`;
  if (s.pattern !== undefined)
    text += `.regex(new RegExp(${JSON.stringify(s.pattern)},"u"))`;
  if (s.description?.startsWith("Canonical integer in 1..2147483647"))
    text +=
      ".refine(value => /^[0-9]+(?![\\s\\S])/u.test(value) && BigInt(value) <= BigInt(2147483647))";
  return text;
}
export function inspectProjectMcpRecommendations(spec) {
  assert.equal(spec.info.version, provenance.openapiVersion);
  const path = spec.paths["/v1/projects/{projectId}/mcp-recommendations"],
    schemas = spec.components.schemas;
  assert.equal(path.get.operationId, "getProjectMcpRecommendations");
  assert.equal(path.put.operationId, "replaceProjectMcpRecommendations");
  assert.equal(path.put["x-kokoro-idempotency"], "natural");
  assert.equal(schemas.ProjectMcpRecommendationRef.oneOf.length, 3);
  assert.deepEqual(schemas.ReplaceProjectMcpRecommendationsRequest.required, [
    "expected_state_version",
    "recommendations",
  ]);
  const faults = Object.fromEntries(
    Object.entries(path.put.responses)
      .filter(([status]) => status !== "200")
      .map(([status, response]) => [
        status,
        response.content["application/json"].schema,
      ]),
  );
  return {
    schemas,
    faults,
    faultStatuses: Object.fromEntries(["get", "put"].map(method => [method.toUpperCase(), Object.keys(path[method].responses).filter(status => status !== "200").map(Number)])),
    id: schemas.ProjectMcpRecommendations.properties.data.properties.project_id,
  };
}
