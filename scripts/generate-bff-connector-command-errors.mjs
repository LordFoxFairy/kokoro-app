import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { existsSync, realpathSync } from "node:fs"
import { readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const source = resolve(root, "src/generated/bff-connector-command-errors.json")
const output = resolve(root, "src/generated/bff-connector-command-errors.ts")
const ownerCommit = "a9a6918d47e1f2654edf8720c561ee06eb57a78c"
const sourceSha256 = "5c12e237e03a6be446a564034ec5c18965e996be24ddeb40807ec4b9b074d83d"

export function renderConnectorCommandErrors(bytes) {
  assert.equal(createHash("sha256").update(bytes).digest("hex"), sourceSha256, "BFF connector error profile digest drift")
  const policy = JSON.parse(bytes.toString("utf8"))
  assert.equal(policy.owner, "kokoro-bff")
  assert.equal(policy.profile, "connector-command-recovery-errors")
  assert.equal(policy.version, "1.1.0")
  assert.equal(policy.visibility, "browser-private")
  assert.equal(policy.automatic_retries, false)
  assert.equal(policy.new_command_authorized, false)
  return `// Generated by scripts/generate-bff-connector-command-errors.mjs. Do not edit.\n\nexport const BFF_CONNECTOR_COMMAND_ERROR_PROVENANCE = ${JSON.stringify({ ownerCommit, sourceSha256, profileVersion: policy.version }, null, 2)} as const;\n\nexport const BFF_CONNECTOR_COMMAND_ERROR_POLICY = ${JSON.stringify(policy, null, 2)} as const;\n`
}

async function main() {
  const mode = process.argv.slice(2).join(" ")
  assert.ok(mode === "--write" || mode === "--check", "expected --write or --check")
  const rendered = renderConnectorCommandErrors(await readFile(source))
  if (mode === "--write") await writeFile(output, rendered)
  else assert.equal(await readFile(output, "utf8"), rendered, "generated BFF connector error profile drift")
  process.stdout.write(`BFF connector error profile ${mode.slice(2)} passed\n`)
}

if (process.argv[1] && existsSync(process.argv[1]) && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))) await main()
