import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
export function renderSessionShareMetadata(bytes, provenance) {
  assert.equal(provenance.owner, "kokoro-bff");
  assert.equal(provenance.candidate, false);
  assert.equal(provenance.owner_commit, "2e737cad9649460dc477fc7d96ba593783fef619");
  assert.equal(provenance.source_path, "contract/openapi/browser/v1/session-share-metadata.json");
  assert.equal(createHash("sha256").update(bytes).digest("hex"), provenance.source_sha256);
  assert.equal(provenance.source_sha256, "112d6e9be1f3969b7820f85a06e627966b72d669b02898d7f57f64e18d03bb2f");
  const spec = JSON.parse(bytes), projection = spec["x-kokoro-projection"];
  assert.equal(projection.profile, provenance.profile);
  assert.equal(projection.version, provenance.profile_version);
  assert.deepEqual(projection.source, provenance.canonical_source);
  assert.deepEqual(projection.source, { path: "contract/openapi/v1/openapi.yaml", version: "29.1.0", sha256: "4e4ce620887b1a1a431a9346d0d259aa5bed3bd5af06f4428f11e9054173418e" });
  assert.equal(spec.info.version, projection.source.version);
  const path = "/v1/sessions/{id}/share", resource = spec.paths[path], operation = resource.get;
  assert.deepEqual(Object.keys(spec.paths), [path]);
  assert.deepEqual(Object.keys(resource), ["parameters", "get"]);
  assert.equal(operation.operationId, projection.operation_id);
  assert.equal(operation.operationId, "getSessionShareMetadata");
  assert.equal(operation["x-kokoro-owner"], "kokoro-bff");
  assert.equal(operation["x-kokoro-idempotency"], "none");
  assert.equal(operation["x-kokoro-permission"], "chat.read");
  assert.equal(operation.requestBody, undefined);
  const dereference = (schema) => {
    if (!schema.$ref) return schema;
    assert.match(schema.$ref, /^#\/components\/(?:parameters|schemas|responses)\/[^/]+$/u);
    const value = schema.$ref.slice(2).split("/").reduce((node, key) => node[key], spec);
    assert.ok(value); return value;
  };
  function render(input) {
    const s = dereference(input);
    if (Array.isArray(s.type)) { assert.deepEqual(s.type, ["string", "null"]); return `${render({ ...s, type: "string" })}.nullable()`; }
    if (s.oneOf) return `z.union([${s.oneOf.map(render).join(", ")}])`;
    if (s.type === "null") return "z.null()";
    if (s.enum) { assert.equal(s.type, "string"); return `z.enum(${JSON.stringify(s.enum)})`; }
    if (s.type === "object") {
      assert.equal(s.additionalProperties, false);
      return `z.object({${Object.entries(s.properties).map(([key, value]) => `${JSON.stringify(key)}: ${render(value)}${s.required.includes(key) ? "" : ".optional()"}`).join(", ")}}).strict()`;
    }
    assert.equal(s.type, "string");
    return `z.string()${s.minLength === undefined ? "" : `.min(${s.minLength})`}${s.maxLength === undefined ? "" : `.max(${s.maxLength})`}${s.format === "date-time" ? ".datetime({ offset: true })" : ""}`;
  }
  const parameters = [...resource.parameters, ...operation.parameters].map(dereference);
  assert.deepEqual(parameters.map(p => [p.in, p.name, p.required]), [["path", "id", true], ["query", "scope", false], ["query", "project_ref", false]]);
  const statuses = Object.keys(operation.responses).map(Number);
  assert.deepEqual(statuses, [200, 400, 401, 403, 404, 429, 503]);
  const wire = dereference(operation.responses[200].content["application/json"].schema);
  const errors = statuses.filter(status => status !== 200);
  const errorSchema = dereference(operation.responses[503]).content["application/json"].schema;
  for (const status of errors) assert.deepEqual(dereference(dereference(operation.responses[status]).content["application/json"].schema), dereference(errorSchema));
  return `// Generated by scripts/generate-bff-session-share-metadata.mjs; do not edit.\nimport { z } from "zod";\nexport const SESSION_SHARE_METADATA_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const;\nexport const sessionShareMetadataOperation = ${JSON.stringify({ method: "GET", path, operationId: operation.operationId })} as const;\nexport const sessionShareMetadataSessionIdSchema = ${render(parameters[0].schema)};\nexport const sessionShareMetadataScopeSchema = ${render(parameters[1].schema)};\nexport const sessionShareMetadataProjectSchema = ${render(parameters[2].schema)};\nexport const sessionShareMetadataWireSchema = ${render(wire)};\nexport const sessionShareMetadataDataSchema = ${render(wire.properties.data)};\nexport const sessionShareMetadataErrorSchema = ${render(errorSchema)};\nexport const sessionShareMetadataErrorStatuses = ${JSON.stringify(errors)} as const;\nexport type SessionShareMetadata = z.infer<typeof sessionShareMetadataDataSchema>;\n`;
}
async function main() {
  const mode = process.argv[2]; assert.ok(mode === "--write" || mode === "--check");
  const provenance = JSON.parse(await readFile(new URL("contract/bff-session-share-metadata-source.json", root), "utf8"));
  const content = renderSessionShareMetadata(await readFile(new URL("src/generated/bff-session-share-metadata.json", root), "utf8"), provenance);
  const output = new URL("src/generated/bff-session-share-metadata.ts", root);
  if (mode === "--write") await writeFile(output, content); else assert.equal(await readFile(output, "utf8"), content, "Share metadata generated decoder drift");
  process.stdout.write(`Session share metadata ${mode.slice(2)} passed\n`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
