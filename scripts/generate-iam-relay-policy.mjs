import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const pin = JSON.parse(await readFile(new URL('contract/bff-iam-relay-policy-source.json',root),'utf8'))
assert.equal(pin.owner_commit,'34c9f997a4d86f33be2f815c43cd155ed338fe86')
assert.equal(pin.source_path,'contract/iam-relay-policy.json')
const bytes = await readFile(new URL(`contract/vendor/kokoro-bff/${pin.owner_commit}/iam-relay-policy.json`,root))
const digest = createHash('sha256').update(bytes).digest('hex')
assert.equal(digest,pin.source_sha256)
assert.equal(digest,'c88bab0bd1d5529573eee318e50ac2dd41349a03fc84e8b7284416af700a0ebe')
const policy=JSON.parse(bytes)
assert.equal(policy.version,'3.0.0'); assert.equal(pin.version,policy.version); assert.equal(policy.routes['/get-session'],undefined)
const provenance=`// Generated by scripts/generate-iam-relay-policy.mjs. Do not edit.\nexport const IAM_RELAY_POLICY_PROVENANCE=${JSON.stringify({ownerRepository:pin.owner,ownerCommit:pin.owner_commit,policySha256:pin.source_sha256})} as const\n`
const outputs=[['src/generated/iam-relay-policy.json',bytes],['src/generated/iam-relay-provenance.ts',provenance]]
assert.ok(['--write','--check'].includes(process.argv[2]))
for (const [path,value] of outputs) { const file=new URL(path,root); if(process.argv[2]==='--write') await writeFile(file,value); else assert.equal(await readFile(file,'utf8'),value.toString(),'IAM relay generation drift') }
