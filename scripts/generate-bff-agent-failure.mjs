import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { existsSync, realpathSync } from "node:fs"
import { readFile, writeFile } from "node:fs/promises"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import YAML from "yaml"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const sourcePath = join(root, "src/generated/bff-public-openapi.yaml")
const outputPath = join(root, "src/generated/bff-agent-failure.ts")
const ownerCommit = "fb9dc4df1679e2d7c97842efcd2fb3bcae297939"
const expectedDigest = "86638da86d786e91c81da9e5dd891dee88ef2ca033579866f5ebc6dd6113c00f"
const expectedVersion = "28.12.0"
const expectedChatMessageFingerprint = "d69b983fd87600f5c180494b27989d5eb2b32c12284bf5c7530930e3099c0bf6"

const digest = (value) => createHash("sha256").update(value).digest("hex")

function stableJson(value) {
  if (Array.isArray(value)) return `[${value.map(stableJson).join(",")}]`
  if (value !== null && typeof value === "object") {
    return `{${Object.keys(value)
      .sort()
      .map((key) => `${JSON.stringify(key)}:${stableJson(value[key])}`)
      .join(",")}}`
  }
  return JSON.stringify(value)
}

export function inspectBffAgentFailureContract(spec) {
  assert.equal(spec?.info?.version, expectedVersion, "BFF public OpenAPI version drift")
  const chatMessage = spec?.components?.schemas?.ChatMessage
  assert.ok(chatMessage, "missing BFF ChatMessage schema")
  assert.equal(digest(stableJson(chatMessage)), expectedChatMessageFingerprint, "BFF ChatMessage failure fragment drift")

  const schemas = spec.components.schemas
  const privateReads = structuredClone([schemas.ChatMessageRead, schemas.OrderedAssistantMessageRead, schemas.CancelledAssistantMessageRead])
  const sourceSchemas = [schemas.ChatMessageRead,schemas.OrderedAssistantMessageRead,schemas.CancelledAssistantMessageRead,schemas.RegeneratedAssistantMessageRead]
  const closedFingerprint=digest(stableJson(sourceSchemas))
  assert.equal(closedFingerprint,"795871baac08082c815fe7ef106e589de2859dbf166f9dcb7973bb8ec0aabca1","BFF regenerated private graph drift")
  privateReads[0].oneOf=privateReads[0].oneOf.filter(item=>item.$ref!=="#/components/schemas/RegeneratedAssistantMessageRead")
  delete privateReads[1].properties.regenerated_from_message_id
  delete privateReads[2].properties.regenerated_from_message_id
  assert.equal(digest(stableJson(privateReads)), "86e632ab432cc13b6b3c3dcd6336949518d08d486484d8371c2c373f0ac8d896", "BFF private cancellation guard drift")
  const cancelledStatus = schemas.CancelledAssistantMessageRead.properties.terminal_status.const
  const roles = chatMessage.properties.role.enum
  const failure = chatMessage.properties.failure
  const codes = failure.properties.code.enum
  const retryableCodes = failure.then.properties.code.enum
  const tuples = [
    ...codes.map((code) => ({ source: failure.properties.source.const, code, retryable: false })),
    ...retryableCodes.map((code) => ({ source: failure.properties.source.const, code, retryable: true })),
  ]

  assert.equal(codes.length, 11, "BFF Agent failure code count drift")
  assert.equal(retryableCodes.length, 2, "BFF retryable Agent failure code count drift")
  assert.equal(tuples.length, 13, "BFF Agent failure tuple count drift")
  return { roles: [...roles], tuples, cancelledStatus }
}

export function renderBffAgentFailureArtifact(contract) {
  const roles = contract.roles.map((role) => `  ${JSON.stringify(role)},`).join("\n")
  const tuples = contract.tuples
    .map(({ source, code, retryable }) => `  { source: ${JSON.stringify(source)}, code: ${JSON.stringify(code)}, retryable: ${retryable} },`)
    .join("\n")
  return `// Generated by scripts/generate-bff-agent-failure.mjs. Do not edit.\n\nexport const BFF_AGENT_FAILURE_PROVENANCE = {\n  ownerCommit: ${JSON.stringify(ownerCommit)},\n  sourceSha256: ${JSON.stringify(expectedDigest)},\n  openapiVersion: ${JSON.stringify(expectedVersion)},\n} as const\n\nexport const BFF_PRIVATE_CANCELLED_STATUS = ${JSON.stringify(contract.cancelledStatus)} as const\n\nexport const BFF_CHAT_MESSAGE_ROLES = [\n${roles}\n] as const\n\nexport const BFF_AGENT_FAILURE_TUPLES = [\n${tuples}\n] as const\n\nexport type BffAgentFailureTuple = (typeof BFF_AGENT_FAILURE_TUPLES)[number]\n`
}

async function main() {
  const mode = process.argv[2]
  assert.ok(mode === "--write" || mode === "--check", "expected --write or --check")
  const source = await readFile(sourcePath)
  assert.equal(digest(source), expectedDigest, "BFF public OpenAPI owner digest drift")
  const rendered = renderBffAgentFailureArtifact(inspectBffAgentFailureContract(YAML.parse(source.toString("utf8"))))

  if (mode === "--write") {
    await writeFile(outputPath, rendered)
  } else {
    assert.equal(await readFile(outputPath, "utf8"), rendered, "generated BFF Agent failure artifact drift")
  }
  process.stdout.write(`BFF Agent failure artifact ${mode.slice(2)} passed (owner SHA-256 ${expectedDigest})\n`)
}

if (process.argv[1] && existsSync(process.argv[1]) && realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url))) await main()
