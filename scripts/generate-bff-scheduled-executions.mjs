import assert from "node:assert/strict"
import { createHash } from "node:crypto"
import { cp, mkdtemp, readFile, readdir, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import { fileURLToPath } from "node:url"
import { createClient } from "@hey-api/openapi-ts"
import YAML from "yaml"

const root = fileURLToPath(new URL("../", import.meta.url))
const output = join(root, "src/generated/bff-scheduled-executions")
const operations = {
  list: ["/v1/scheduled-tasks/executions", "get", "listScheduledTaskExecutions"],
}

function scheduledExecutionsDocument(spec) {
  const paths = {}
  const statuses = {}
  for (const [name, [path, method, operationId]] of Object.entries(operations)) {
    const item = spec.paths?.[path]
    const operation = item?.[method]
    assert.equal(operation?.operationId, operationId)
    paths[path] ??= { parameters: item.parameters }
    paths[path][method] = operation
    statuses[name] = Object.keys(operation.responses).map(Number)
  }
  const components = { securitySchemes: spec.components.securitySchemes }
  const seen = new Set()
  function visit(value) {
    if (value === null || typeof value !== "object") return
    for (const [key, item] of Object.entries(value)) {
      if (key !== "$ref") { visit(item); continue }
      if (seen.has(item)) continue
      seen.add(item)
      const match = /^#\/components\/([^/]+)\/([^/]+)$/u.exec(item)
      assert.ok(match, `Unsupported Scheduled execution reference: ${item}`)
      const [, group, name] = match
      const target = spec.components?.[group]?.[name]
      assert.ok(target, `Missing Scheduled execution component: ${item}`)
      ;(components[group] ??= {})[name] = target
      visit(target)
    }
  }
  visit(paths)
  return { document: { openapi: spec.openapi, info: spec.info, servers: spec.servers, security: spec.security, paths, components }, statuses }
}

const mode = process.argv[2]
assert.ok(mode === "--check" || mode === "--write")
const pin = JSON.parse(await readFile(join(root, "contract/bff-scheduled-executions-source.json"), "utf8"))
assert.match(pin.owner_commit, /^[0-9a-f]{40}$/u)
assert.equal(pin.source_path, "contract/openapi/v1/openapi.yaml")
const source = join(root, "contract/vendor/kokoro-bff", pin.owner_commit, "openapi.yaml")
const bytes = await readFile(source)
assert.equal(createHash("sha256").update(bytes).digest("hex"), pin.source_sha256)
const spec = YAML.parse(bytes.toString("utf8"))
assert.equal(spec.info.version, pin.openapi_version)
const { document, statuses } = scheduledExecutionsDocument(spec)
const staging = await mkdtemp(join(tmpdir(), "kokoro-scheduled-executions-"))
const generated = join(staging, "output")
try {
  await createClient({
    input: document,
    output: { path: generated, entryFile: false, module: { extension: "" }, tsConfigPath: join(root, "tsconfig.json") },
    plugins: ["@hey-api/typescript", { name: "zod", compatibilityVersion: 3, requests: false, responses: true,
      $resolvers: {
        object(ctx) {
          const base = ctx.nodes.base(ctx)
          return ctx.schema.additionalProperties?.type === "never" ? base.attr("strict").call() : base
        },
      },
    }],
    logs: { level: "silent" },
  })
  await writeFile(join(generated, "provenance.ts"),
    `// Generated by scripts/generate-bff-scheduled-executions.mjs. Do not edit.\nexport const BFF_SCHEDULED_EXECUTIONS_SOURCE = ${JSON.stringify(pin, null, 2)} as const\nexport const SCHEDULED_EXECUTION_STATUSES = ${JSON.stringify(statuses, null, 2)} as const\n`)
  const files = (await readdir(generated)).sort()
  assert.deepEqual(files, ["provenance.ts", "types.gen.ts", "zod.gen.ts"])
  if (mode === "--write") {
    await rm(output, { recursive: true, force: true })
    await cp(generated, output, { recursive: true })
  } else {
    assert.deepEqual((await readdir(output)).sort(), files)
    for (const name of files) assert.deepEqual(await readFile(join(output, name)), await readFile(join(generated, name)), name)
  }
} finally {
  await rm(staging, { recursive: true, force: true })
}
