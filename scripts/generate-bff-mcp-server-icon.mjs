import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const provenance = JSON.parse(await readFile(new URL("contract/bff-mcp-server-icon-source.json", root), "utf8"));
assert.equal(provenance.owner, "kokoro-bff");
assert.equal(provenance.candidate, false);
assert.equal(provenance.source_path, "contract/openapi/browser/v1/mcp-server-icon.json");
assert.match(provenance.owner_commit, /^[0-9a-f]{40}$/u);
const bytes = await readFile(new URL("src/generated/bff-mcp-server-icon.json", root));
assert.equal(createHash("sha256").update(bytes).digest("hex"), provenance.source_sha256);
const spec = JSON.parse(bytes), policy = spec["x-kokoro-media-policy"];
assert.equal(policy.visibility, "browser-private");
assert.equal(policy.owner, provenance.owner);
assert.equal(policy.profile, provenance.profile);
assert.equal(policy.version, provenance.profile_version);
assert.equal(spec.info.version, provenance.profile_version);
assert.deepEqual(Object.keys(spec.paths), [policy.path]);
assert.equal(policy.path, "/browser/v1/mcp/servers/{server_id}/icon");
const operation = spec.paths[policy.path].get;
assert.equal(operation.operationId, policy.operation_id);
assert.equal(policy.method, "GET");
assert.equal(policy.body, false); assert.equal(policy.query, false); assert.equal(policy.command_headers, false);
assert.equal(policy.automatic_retries, false); assert.equal(policy.new_command_authorized, false);
assert.equal(policy.max_bytes, 1_048_576);
assert.deepEqual(Object.keys(operation.responses[200].content), policy.success.content_types);
function render(s) {
  if ("const" in s) return `z.literal(${JSON.stringify(s.const)})`;
  if (s.oneOf) return s.oneOf.length === 1 ? render(s.oneOf[0]) : `z.union([${s.oneOf.map(render).join(", ")}])`;
  if (s.type === "object") {
    assert.equal(s.additionalProperties, false);
    return `z.object({${Object.entries(s.properties).map(([key, value]) => `${JSON.stringify(key)}: ${render(value)}${s.required.includes(key) ? "" : ".optional()"}`).join(", ")}}).strict()`;
  }
  assert.equal(s.type, "string");
  return `z.string()${s.pattern ? `.regex(new RegExp(${JSON.stringify(s.pattern)}, "u"))` : ""}`;
}
const errors = Object.entries(operation.responses).filter(([status]) => status !== "200");
const tuples = errors.flatMap(([status, response]) => response.content["application/json"].schema.oneOf.map(schema => ({ status: Number(status), code: schema.properties.error.properties.code.const, retryable: schema.properties.error.properties.retryable.const })));
assert.deepEqual([...tuples].sort((a,b) => a.code.localeCompare(b.code)), [...policy.errors].sort((a,b) => a.code.localeCompare(b.code)));
const content = `// Generated by scripts/generate-bff-mcp-server-icon.mjs; do not edit.\nimport { z } from "zod";\nexport const MCP_SERVER_ICON_PROVENANCE = ${JSON.stringify(provenance, null, 2)} as const;\nexport const MCP_SERVER_ICON_POLICY = ${JSON.stringify(policy, null, 2)} as const;\nexport const mcpServerIconIdSchema = ${render(operation.parameters[0].schema)};\nexport const mcpServerIconErrors = {\n${errors.map(([status, response]) => `${JSON.stringify(status)}: ${render(response.content["application/json"].schema)}`).join(",\n")}\n} as const;\n`;
const target = new URL("src/generated/bff-mcp-server-icon.ts", root);
if (process.argv[2] === "--write") await writeFile(target, content);
else { assert.equal(process.argv[2], "--check"); assert.equal(await readFile(target, "utf8"), content); }
